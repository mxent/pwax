#!/usr/bin/env node
/**
 * Server-side render a Pwax component to an HTML string.
 *
 * The PHP side ({@see \Mxent\Pwax\Pwa\Ssr\Prerenderer}) spawns this script once per
 * prerendered response (cached on the component hash + data digest), feeds it a JSON
 * payload on stdin, and reads `{ok, html, serializedState, errors}` on stdout. Nothing
 * else goes to stdout; diagnostics go to stderr, so a stray console.log cannot corrupt
 * the result the PHP side parses.
 *
 * The payload is the same `Component` the browser already receives — `template`,
 * `script`, `style`, `scope` — plus the controller `data` the route passed to
 * `pwaxRender()`. The script is evaluated as an ES module via a `data:` URL, so the
 * author's `export default { … }` resolves exactly as it does in the browser. Top-level
 * references to the global `Vue` work because the module is evaluated in Node's module
 * scope, and the render functions generated by `@vue/compiler-dom` receive the Vue
 * namespace as a parameter.
 *
 * `@vue/server-renderer` and `@vue/compiler-dom` are optional peer dependencies, just as
 * `@vue/compiler-dom` is for `bin/compile-templates.mjs`. An application that has not
 * opted into SSR never installs them; the doctor reports the missing dependency with the
 * install command rather than letting the request fail.
 *
 *   npm install --save-dev @vue/server-renderer@<the version Pwax vendors>
 *
 * The version guard below ensures the server renderer and the compiler match the Vue
 * runtime Pwax ships, so the HTML this script produces hydrates cleanly in the browser.
 */

import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

const write = (payload) => process.stdout.write(JSON.stringify(payload));

const fail = (message, extra = {}) => {
    write({ ok: false, message, ...extra });
    process.exit(0);
};

const read = () =>
    new Promise((resolve, reject) => {
        let raw = '';

        process.stdin.setEncoding('utf8');
        process.stdin.on('data', (chunk) => (raw += chunk));
        process.stdin.on('end', () => resolve(raw));
        process.stdin.on('error', reject);
    });

let input;

try {
    input = JSON.parse((await read()) || '{}');
} catch (error) {
    fail(`Could not read the SSR payload from stdin: ${error.message}`);
}

const wanted = typeof input.version === 'string' ? input.version : '';
const install = `\`npm install --save-dev @vue/server-renderer@${wanted || 'latest'}\``;

let compiler;

try {
    compiler = await import('@vue/compiler-dom');
} catch {
    fail(
        'The optional peer dependency @vue/compiler-dom is not installed. Run ' +
            `\`npm install --save-dev @vue/compiler-dom@${wanted || 'latest'}\` in your application.`
    );
}

let renderer;

try {
    renderer = await import('@vue/server-renderer');
} catch {
    fail(
        'The optional peer dependency @vue/server-renderer is not installed. Run ' +
            `${install} in your application, or set pwax.ssr.enabled to false.`
    );
}

/*
 * The server renderer, the compiler and the shipped Vue runtime must all be the same
 * version. A mismatch emits HTML the runtime cannot hydrate, and the failure surfaces at
 * hydration time in the browser with an error that names none of them. Refusing here costs
 * one clear message instead. Same guard as `bin/compile-templates.mjs`.
 */
let installedCompiler = '';
let installedRenderer = '';

try {
    installedCompiler = require('@vue/compiler-dom/package.json').version || '';
} catch {
    // Resolvable as a module but not as a manifest — skip the comparison.
}

try {
    installedRenderer = require('@vue/server-renderer/package.json').version || '';
} catch {
    // Same.
}

if (wanted && installedRenderer && installedRenderer !== wanted) {
    fail(
        `@vue/server-renderer ${installedRenderer} does not match the Vue runtime Pwax ships ` +
            `(${wanted}). Install the matching version: ${install}`
    );
}

if (wanted && installedCompiler && installedCompiler !== wanted) {
    fail(
        `@vue/compiler-dom ${installedCompiler} does not match the Vue runtime Pwax ships ` +
            `(${wanted}). Install the matching version: \`npm install --save-dev @vue/compiler-dom@${wanted}\`.`
    );
}

const { renderToString } = renderer;
const { compile } = compiler;

// The Vue runtime, imported once. The generated render functions reference the global
// `Vue` (see `runtimeGlobalName` below), so the same object is passed into the compiled
// function's scope. Same trick the render-function store uses on the client.
const Vue = await import('vue');

/**
 * Evaluate a component's inline `script` as an ES module and return its default export.
 *
 * The script is the same string the browser receives as an inline module — `export
 * default { … }` — so evaluating it as a module yields the component options directly,
 * with no `new Function` and no CSP concern (this is Node, not the browser). A data: URL
 * is the simplest way to hand a string to `import()`; Node treats it as a module.
 *
 * @param {string} source
 * @returns {Promise<any>}
 */
async function evaluateModule(source) {
    if (!source || !source.trim()) {
        return {};
    }

    const url = 'data:text/javascript;charset=utf-8,' + encodeURIComponent(source);

    return import(url);
}

/**
 * Compile a template string to a render function, using the same options as
 * `bin/compile-templates.mjs` so the server's output matches what the browser compiles.
 *
 * @param {string} template
 * @returns {Function}
 */
function compileTemplate(template) {
    const { code } = compile(template, {
        mode: 'function',
        hoistStatic: true,
        prefixIdentifiers: true,
        runtimeGlobalName: 'Vue',
        ssr: false,
    });

    // The generated chunk ends in `return function render(…)`, so evaluating it inside a
    // function yields the function itself — same trick the render-function store uses.
    return new Function('Vue', code)(Vue);
}

/**
 * Render one component to an HTML string.
 *
 * @returns {Promise<{ok: boolean, html?: string, serializedState?: any, errors?: Record<string,string>}>}
 */
async function renderOne() {
    const component = input.component || {};
    const data = input.data || {};
    const scope = component.scope || null;
    const template = component.template || '';
    const script = component.script || '';
    // The content template the client app uses (e.g. `<main><router-view></router-view>
    // </main>`). The server must render the same wrapper so the prerendered HTML matches
    // the client's virtual DOM and hydrates without a mismatch. When absent, the default
    // matches the runtime's `DEFAULT_CONTENT`.
    const contentTemplate = input.contentTemplate || '<main><router-view></router-view></main>';

    const module = await evaluateModule(script);
    const options = typeof module.default === 'function' ? module.default() : { ...(module.default || {}) };

    // The author's own `render` or `template` wins outright; otherwise the Blade template
    // applies. Mirrors `toComponentOptions` in the client runtime.
    if (!options.render && !options.template && template) {
        options.render = compileTemplate(template);
    }

    // Props are the controller data. A component that declares `props` consumes them; one
    // that does not receives them as the root state for SSR purposes only. They are also
    // echoed back as `serializedState` so the client can hydrate without a re-fetch.
    options.props = options.props || Object.keys(data);

    // The scope attribute the StyleScoper stamped onto the template's elements. Applying
    // it here keeps SSR output visually consistent with the hydrated client.
    if (scope) {
        options.__pwaxScope = scope;
    }

    // Capture the resolved component state so the client hydration starts from the same
    // values the server rendered with. Vue clears the root instance after `renderToString`
    // returns, so reading `_instance` afterwards yields nulls; instead, wrap `data()` and
    // `setup()` to retain their results. The wrappers are removed before the options are
    // handed to `createSSRApp`-as-data, so they do not leak into the client payload — the
    // client receives the original `script` in its own inline module.
    let captured = { ...data };

    if (typeof options.data === 'function') {
        const originalData = options.data;
        options.data = function ssrDataCapture(...args) {
            const result = originalData.apply(this, args);
            captured = { ...captured, ...result };
            return result;
        };
    }

    if (typeof options.setup === 'function') {
        const originalSetup = options.setup;
        options.setup = function ssrSetupCapture(...args) {
            const result = originalSetup.apply(this, args);
            if (result && typeof result.then === 'function') {
                return result.then((resolved) => {
                    captured = { ...captured, ...resolved };
                    return resolved;
                });
            }
            captured = { ...captured, ...result };
            return result;
        };
    }

    // Render the page component wrapped in the same content template the client app
    // uses, so the server HTML matches the client's virtual DOM and hydrates without a
    // mismatch. The client app renders `<main><router-view></router-view></main>` where
    // `router-view` resolves to the PwaxPage component, which in turn renders the page
    // component via `<component :is="component">`. For SSR we shortcut that to a
    // `router-view` global component that renders the page component directly with the
    // controller data as props — the PwaxPage wrapper's conditional branches (error,
    // loader) all resolve to the component on a successful prerender, so the output is
    // identical.
    const pageComponent = options;
    const propsData = data;
    const app = Vue.createSSRApp({
        template: contentTemplate,
    });

    // Register `router-view` as a global component that renders the page component with
    // the controller data as props, so the content template's `<router-view>` resolves to
    // it. This mirrors what the client produces when PwaxPage has `component` set and no
    // error.
    app.component('router-view', {
        render() {
            return Vue.h(pageComponent, propsData);
        },
    });

    // Also register `router-link` as a pass-through `<a>`, since page templates may use
    // `<RouterLink>` / `<router-link>` for navigation. On the server it renders as a plain
    // `<a>` with the `to` value as `href`, which matches what the client renders.
    app.component('router-link', {
        props: { to: { type: [String, Object], default: '' } },
        template: '<a :href="typeof to === \'string\' ? to : to.path || \'\'"><slot></slot></a>',
    });

    const html = await renderToString(app);

    let serializedState = data;

    try {
        // Prefer the captured state; fall back to the input data for components that
        // consumed it purely as props (no `data()` or `setup()`).
        serializedState = JSON.parse(JSON.stringify(captured));
    } catch {
        serializedState = data;
    }

    return { ok: true, html, serializedState };
}

try {
    const result = await renderOne();
    write(result);
} catch (error) {
    write({
        ok: false,
        message: error && error.message ? error.message : String(error),
        errors: { _: error && error.stack ? String(error.stack) : String(error) },
    });
}